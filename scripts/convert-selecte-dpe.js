#!/usr/bin/env node
'use strict';

/*
	Converts seleCte's trained MdMC model (the probability-estimation dicts
	under src/seleCte/pcg/preprocessing/probability_estimation_dicts/ in
	https://github.com/robilouis/seleCte) into the single Lua data file the
	seleCte Lua port reads:

	    node scripts/convert-selecte-dpe.js <path-to-seleCte-checkout>

	Output: Loenn/library/selecte/dpe_data.lua

	Every dict is `{ "#mdmc_matrix": mask, "<pattern>": { "<symbol>": prob } }`
	with the distribution zero-filled over the whole vocabulary. The zeros carry
	no information (generation never samples a zero-probability symbol), so
	they are dropped here: the 19 shipped dicts collapse from ~600KB of JSON to
	well under 100KB of Lua. Within a pattern the symbols are sorted by
	probability (highest first, ties by vocabulary order) and patterns by
	vocabulary order, so the output is a pure function of the model and the
	weighted draw in rng.lua usually stops after its first entry.

	Only needed when retraining: the committed dpe_data.lua already holds the
	model that ships with seleCte 0.10.0. Retraining itself does not need this
	script at all - the Lua port can estimate a dict from the open map or from
	a folder of .bin files directly (see Loenn/library/selecte/mdmc.lua).
*/

const fs = require('fs');
const path = require('path');

const repo = process.argv[2];
if (!repo) {
	console.error('usage: node scripts/convert-selecte-dpe.js <path-to-seleCte-checkout>');
	process.exit(2);
}

const dictsDir = path.join(repo, 'src', 'seleCte', 'pcg', 'preprocessing', 'probability_estimation_dicts');
if (!fs.existsSync(dictsDir)) {
	console.error(`no probability_estimation_dicts under ${repo}`);
	process.exit(2);
}

const outPath = path.join(__dirname, '..', 'Loenn', 'library', 'selecte', 'dpe_data.lua');

// A dict's Lua key: `pe_d5_full` stays as is, `3_000011012` -> `fg_3`,
// `bg_3_000011012` -> `bg_3`. The mask suffix moves into the `mask` field.
function luaKey(stem) {
	if (stem === 'pe_d5_full') return stem;
	const m = stem.match(/^(bg_)?(\w+?)_(\d+)$/);
	if (!m) throw new Error(`unexpected dict name ${stem}`);
	return `${m[1] || 'fg_'}${m[2]}`;
}

function luaString(s) {
	return '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

const VOCABULARY = ['0', '1', '^', '<', 'v', '>', 'D', 'C', '_', 'O', 'Q', 'W', 'S', 'B', 'R', 'F', 'L',
	'2', '3', '4', '5', '6', '7', '8', '9', 'a', 'b', 'c', 'd', 'e'];
const rank = (sym) => {
	const i = VOCABULARY.indexOf(sym);
	return i < 0 ? VOCABULARY.length : i;
};
const comparePatterns = (a, b) => {
	for (let i = 0; i < Math.max(a.length, b.length); i++) {
		const d = rank(a[i] || '') - rank(b[i] || '');
		if (d) return d;
	}
	return a < b ? -1 : a > b ? 1 : 0;
};

const files = fs.readdirSync(dictsDir).filter((f) => f.endsWith('.json')).sort();
const lines = [];
lines.push('-- dpe_data.lua - the trained MdMC model that ships with seleCte 0.10.0');
lines.push('-- (https://github.com/robilouis/seleCte, MIT). GENERATED by');
lines.push('-- scripts/convert-selecte-dpe.js - do not edit by hand.');
lines.push('--');
lines.push('-- Each dict is { mask = <flattened 3x3 MdMC mask>, patterns = { [pattern] =');
lines.push('-- { symbol, probability, symbol, probability, ... } } }. Zero-probability');
lines.push('-- entries are omitted; the Python side zero-fills over the vocabulary, which');
lines.push('-- changes nothing about what gets sampled.');
lines.push('--');
lines.push('--   pe_d5_full  foreground, all 824 vanilla rooms (what level_generation uses)');
lines.push('--   fg_1..fg_9  foreground, one vanilla chapter each');
lines.push('--   bg_1..bg_9  background tilesets, one vanilla chapter each');
lines.push('');
lines.push('return {');

let totalPatterns = 0;
let totalEntries = 0;
for (const f of files) {
	const stem = path.basename(f, '.json');
	const raw = JSON.parse(fs.readFileSync(path.join(dictsDir, f), 'utf8'));
	const mask = raw['#mdmc_matrix'] || stem.split('_').pop();
	delete raw['#mdmc_matrix'];

	lines.push(`\t${luaKey(stem)} = {`);
	lines.push(`\t\tmask = ${luaString(mask)},`);
	lines.push('\t\tpatterns = {');
	for (const pattern of Object.keys(raw).sort(comparePatterns)) {
		const dist = raw[pattern];
		const pairs = Object.entries(dist)
			.filter(([, p]) => p > 0)
			.sort(([sa, pa], [sb, pb]) => pb - pa || rank(sa) - rank(sb))
			.map(([sym, p]) => `${luaString(sym)}, ${p}`);
		totalPatterns += 1;
		totalEntries += pairs.length;
		lines.push(`\t\t\t[${luaString(pattern)}] = { ${pairs.join(', ')} },`);
	}
	lines.push('\t\t},');
	lines.push('\t},');
	console.log(`  ${stem} -> ${luaKey(stem)} (${Object.keys(raw).length} patterns)`);
}
lines.push('}');
lines.push('');

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, lines.join('\n'));
console.log(`wrote ${outPath}: ${files.length} dicts, ${totalPatterns} patterns, ${totalEntries} non-zero entries`);
